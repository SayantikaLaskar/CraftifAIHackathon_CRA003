import { Fragment } from 'react';
import clsx from 'clsx';
import { ArrowRight, Cpu, FileCode2, Gauge, MonitorSmartphone, Server } from 'lucide-react';
import { Badge, Card, CardHeader, Empty, LiveDot, PageHeader, SimBadge, Skeleton } from '../../components/ui.tsx';
import { useResource, useRealtime, type Device } from '../../lib/api.ts';
import { ago, pct } from '../../lib/format.ts';
import { useState, useEffect } from 'react';

interface PipegenReport {
  status: 'pending' | 'ok';
  source?: string;
  engines?: { model: string; precision: string; throughputFps: number; latencyMs: number; accuracy?: string; gpu?: string }[];
}

const NODES = [
  { label: 'Camera', sub: 'USB / RTSP · 1080p30', icon: MonitorSmartphone },
  { label: 'nvstreammux', sub: 'batch per line' },
  { label: 'Person detector', sub: 'nvinfer · TensorRT', accent: true },
  { label: 'nvtracker', sub: 'NvDCF' },
  { label: 'Hand landmarks', sub: '21 pts · TensorRT', accent: true },
  { label: 'msgconv → JSON', sub: 'keypoint frames' },
  { label: 'takt_edge.py', sub: 'bridge → /api/ingest', icon: FileCode2 },
  { label: 'Takt server', sub: 'cycle engine', icon: Server },
];

export default function Edge() {
  const { data } = useResource<Device[]>('/api/devices', { every: 5000 });
  const { data: report } = useResource<PipegenReport>('/api/pipegen');
  const [devices, setDevices] = useState<Device[]>([]);
  useEffect(() => { if (data) setDevices(data); }, [data]);
  useRealtime(m => { if (m.kind === 'device') setDevices(ds => [...ds.filter(d => d.id !== m.device.id), m.device].sort((a, b) => a.id.localeCompare(b.id))); });

  return (
    <>
      <PageHeader eyebrow="Perception layer" title="Edge &amp; PipeGen"
        subtitle="Every station camera runs a CraftifAI PipeGen pipeline: a DeepStream app with TensorRT engines that streams hand keypoints, never video, to Takt." />

      <Card>
        <CardHeader title="Pipeline graph" subtitle="Generated by PipeGen from pipegen/REQUIREMENT.md (Stage 2 IR → Stage 5 run)" />
        <div className="overflow-x-auto px-5 pb-6 pt-5">
          <div className="flex min-w-max items-center gap-2">
            {NODES.map((n, i) => (
              <Fragment key={n.label}>
                <div className={clsx('flex h-[78px] w-[150px] shrink-0 flex-col justify-center rounded-xl border px-3.5', n.accent ? 'border-brand-100 bg-brand-50' : 'border-line bg-surface-2')}>
                  <div className="flex items-center gap-1.5 text-[13px] font-semibold">{n.icon && <n.icon size={14} className="text-ink-2" />}{n.label}</div>
                  <div className={clsx('mt-0.5 text-[11.5px]', n.accent ? 'text-brand-700' : 'text-muted')}>{n.sub}</div>
                </div>
                {i < NODES.length - 1 && <ArrowRight size={14} className="shrink-0 text-axis" />}
              </Fragment>
            ))}
          </div>
        </div>
      </Card>

      <h2 className="mb-3 mt-8 text-[17px] font-semibold tracking-tight">Edge devices</h2>
      {!data ? <Skeleton className="h-40" /> : (
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {devices.map(d => {
            const online = Date.now() - d.lastSeen < 10_000;
            return (
              <Card key={d.id} className="p-5">
                <div className="flex items-start justify-between gap-3">
                  <div className="flex items-center gap-3">
                    <div className="grid size-9 place-items-center rounded-lg bg-sunken text-ink-2">{d.kind === 'browser' ? <MonitorSmartphone size={17} /> : <Cpu size={17} />}</div>
                    <div>
                      <div className="text-[14px] font-semibold">{d.name}</div>
                      <div className="text-[12px] text-muted">{d.pipeline}</div>
                    </div>
                  </div>
                  <span className="flex items-center gap-1.5 text-[12px] text-ink-2"><LiveDot on={online} />{online ? 'Online' : `Seen ${ago(d.lastSeen)}`}</span>
                </div>
                <div className="mt-4 grid grid-cols-3 gap-3 border-t border-line pt-4">
                  <Metric label="Throughput" value={`${d.fps}`} unit="FPS" />
                  <Metric label="Latency" value={`${d.latencyMs}`} unit="ms" />
                  <Metric label="GPU" value={d.gpuUtil === null ? '—' : pct(d.gpuUtil)} />
                </div>
                <div className="mt-4 flex flex-wrap items-center gap-1.5">
                  <Badge tone="brand">{d.precision}</Badge>
                  <Badge>{d.model}</Badge>
                  <Badge>{d.cameras.length} camera{d.cameras.length === 1 ? '' : 's'}</Badge>
                  {d.simulated && <SimBadge />}
                </div>
              </Card>
            );
          })}
        </div>
      )}

      <div className="mt-8 grid gap-4 xl:grid-cols-[minmax(0,1.1fr)_minmax(0,1fr)]">
        <Card className="overflow-hidden">
          <CardHeader title="TensorRT engine report" subtitle="Imported from the PipeGen compiler stage (pipegen/trt_report.json)" />
          {report?.status === 'ok' && report.engines?.length ? (
            <table className="mt-4 w-full text-[13px] tnum">
              <thead><tr className="border-y border-line bg-surface-2 text-left text-[12px] text-muted">
                {['Model', 'Precision', 'Throughput', 'Latency', 'Accuracy', 'GPU'].map(h => <th key={h} className="px-5 py-2.5 font-medium">{h}</th>)}
              </tr></thead>
              <tbody>{report.engines.map(e => (
                <tr key={e.model + e.precision} className="border-b border-line last:border-0">
                  <td className="px-5 py-3 font-medium">{e.model}</td><td className="px-5 py-3"><Badge tone="brand">{e.precision}</Badge></td>
                  <td className="px-5 py-3">{e.throughputFps} FPS</td><td className="px-5 py-3">{e.latencyMs} ms</td>
                  <td className="px-5 py-3">{e.accuracy ?? '—'}</td><td className="px-5 py-3 text-ink-2">{e.gpu ?? '—'}</td>
                </tr>))}
              </tbody>
            </table>
          ) : (
            <Empty icon={<Gauge size={18} />} title="Awaiting PipeGen compile">
              Run PipeGen's compiler stage on the Jetson or GPU host, then save its speed report to <code className="rounded bg-sunken px-1">pipegen/trt_report.json</code>. FP32, FP16 and INT8 engines will be compared here.
            </Empty>
          )}
        </Card>
        <Card>
          <CardHeader title="Connect a PipeGen pipeline" subtitle="Three commands on the edge device" />
          <div className="space-y-3 p-5">
            {[
              ['Generate & compile', 'PipeGen ▸ paste pipegen/REQUIREMENT.md ▸ run all 5 stages'],
              ['Run & stream keypoints', './run.sh | python3 edge/takt_edge.py --server http://<takt-host>:8787 --camera cam-l1-30'],
              ['Replay a recording', 'python3 edge/takt_edge.py --replay takt-keypoints.jsonl --camera cam-live'],
            ].map(([t, c], i) => (
              <div key={t}>
                <div className="mb-1.5 flex items-center gap-2 text-[13px] font-medium"><span className="grid size-5 place-items-center rounded-full bg-ink text-[11px] text-white">{i + 1}</span>{t}</div>
                <pre className="overflow-x-auto rounded-lg bg-[#0d0f12] px-3.5 py-2.5 font-mono text-[12px] leading-relaxed text-[#d8dee9]">{c}</pre>
              </div>
            ))}
          </div>
        </Card>
      </div>
    </>
  );
}

function Metric({ label, value, unit }: { label: string; value: string; unit?: string }) {
  return (
    <div>
      <div className="text-[11.5px] text-muted">{label}</div>
      <div className="mt-0.5 text-[17px] font-semibold tracking-tight tnum">{value}{unit && <span className="ml-0.5 text-[12px] font-normal text-muted">{unit}</span>}</div>
    </div>
  );
}
